import React, { useState } from 'react';
import { ModelEvaluationResult, LLMEvalTaskId, GroundTruthBenchmark } from '../../../types/llmEvaluation';
import { EVALUATION_TASKS_CONFIG, GROUND_TRUTH_DATASETS } from '../../../services/llmGroundTruthService';
import { LLMEvaluationService } from '../../../services/llmEvaluationService';
import { Split, Eye, Sparkles, CheckCircle2, ShieldAlert, Sliders } from 'lucide-react';

interface OutputComparisonViewerProps {
  results: Record<string, ModelEvaluationResult>;
  models: { id: string; name: string; color: string }[];
  currentDomain: string;
}

export const OutputComparisonViewer: React.FC<OutputComparisonViewerProps> = ({ results, models, currentDomain }) => {
  const [selectedTask, setSelectedTask] = useState<LLMEvalTaskId>('extraction');
  const [modelAId, setModelAId] = useState<string>(models[0]?.id || 'gpt-4o');
  const [modelBId, setModelBId] = useState<string>(models[1]?.id || 'claude-3-5-sonnet');
  const [manualScoreA, setManualScoreA] = useState<number | null>(null);
  const [manualScoreB, setManualScoreB] = useState<number | null>(null);

  const benchmark = GROUND_TRUTH_DATASETS[currentDomain] || GROUND_TRUTH_DATASETS['Railway Reservation'];
  const standardizedPrompt = LLMEvaluationService.getStandardizedPrompt(selectedTask, currentDomain, benchmark.rawInputDocument);

  const resA = results[modelAId];
  const resB = results[modelBId];

  const outA = resA?.taskOutputs[selectedTask];
  const outB = resB?.taskOutputs[selectedTask];

  const scoreA = manualScoreA !== null ? manualScoreA : (outA?.score || 0);
  const scoreB = manualScoreB !== null ? manualScoreB : (outB?.score || 0);

  return (
    <div className="space-y-6">
      {/* Selector Control Bar */}
      <div className="glass-card p-6 rounded-2xl border border-white/10 space-y-6">
        <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 border-b border-white/10 pb-4">
          <div className="flex items-center space-x-3">
            <div className="h-10 w-10 rounded-xl bg-blue-500/20 border border-blue-400/40 flex items-center justify-center text-blue-300 shadow-neon-blue">
              <Split className="h-5 w-5" />
            </div>
            <div>
              <h3 className="text-base font-bold text-white font-mono">Split-Screen Output &amp; Explainability Inspector</h3>
              <p className="text-xs text-slate-400 font-light">Inspect identical prompt inputs and compare exact outputs generated by competing models.</p>
            </div>
          </div>
        </div>

        {/* Controls Grid */}
        <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
          <div>
            <label className="text-[11px] font-mono font-bold text-slate-400 block mb-1.5 uppercase">Evaluation Task</label>
            <select
              value={selectedTask}
              onChange={(e) => {
                setSelectedTask(e.target.value as LLMEvalTaskId);
                setManualScoreA(null);
                setManualScoreB(null);
              }}
              className="w-full bg-surface border border-white/10 rounded-xl px-3.5 py-2 text-xs font-mono font-bold text-white focus:outline-none cursor-pointer"
            >
              {EVALUATION_TASKS_CONFIG.map(t => (
                <option key={t.id} value={t.id}>{t.label} ({t.category})</option>
              ))}
            </select>
          </div>

          <div>
            <label className="text-[11px] font-mono font-bold text-cyan-400 block mb-1.5 uppercase">Model A (Left)</label>
            <select
              value={modelAId}
              onChange={(e) => { setModelAId(e.target.value); setManualScoreA(null); }}
              className="w-full bg-surface border border-cyan-500/30 rounded-xl px-3.5 py-2 text-xs font-mono font-bold text-cyan-300 focus:outline-none cursor-pointer"
            >
              {models.map(m => (
                <option key={m.id} value={m.id}>{m.name}</option>
              ))}
            </select>
          </div>

          <div>
            <label className="text-[11px] font-mono font-bold text-violet-400 block mb-1.5 uppercase">Model B (Right)</label>
            <select
              value={modelBId}
              onChange={(e) => { setModelBId(e.target.value); setManualScoreB(null); }}
              className="w-full bg-surface border border-violet-500/30 rounded-xl px-3.5 py-2 text-xs font-mono font-bold text-violet-300 focus:outline-none cursor-pointer"
            >
              {models.map(m => (
                <option key={m.id} value={m.id}>{m.name}</option>
              ))}
            </select>
          </div>
        </div>
      </div>

      {/* Standardized Benchmark Input Prompt Accordion */}
      <div className="glass-card p-5 rounded-2xl border border-white/10 space-y-2">
        <div className="flex items-center justify-between text-xs font-mono font-bold text-slate-300">
          <span className="flex items-center gap-2">
            <span className="h-2 w-2 rounded-full bg-emerald-400 animate-pulse" />
            STANDARDIZED BENCHMARK PROMPT (Same input provided to both models)
          </span>
          <span className="text-[10px] text-slate-500">Task: {selectedTask}</span>
        </div>
        <pre className="p-3.5 rounded-xl bg-black/60 border border-white/5 text-[11px] font-mono text-slate-300 whitespace-pre-wrap leading-relaxed max-h-36 overflow-y-auto">
          {standardizedPrompt}
        </pre>
      </div>

      {/* Split-Screen Outputs */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        {/* Model A Column */}
        <div className="glass-card p-6 rounded-2xl border border-cyan-500/30 shadow-neon-blue space-y-4 flex flex-col justify-between">
          <div className="space-y-3">
            <div className="flex items-center justify-between border-b border-white/10 pb-3">
              <div>
                <span className="text-[10px] font-mono font-bold text-cyan-400 uppercase">MODEL A OUTPUT</span>
                <h4 className="text-sm font-bold text-white font-mono">{resA?.modelName}</h4>
              </div>
              <div className="text-right">
                <span className="text-xl font-black font-mono text-cyan-300">{scoreA}%</span>
                <span className="text-[10px] text-slate-400 block font-mono">
                  {manualScoreA !== null ? '(Overridden)' : outA?.evaluationMode}
                </span>
              </div>
            </div>

            <div className="space-y-1.5 font-mono text-xs text-slate-400">
              <div className="flex justify-between">
                <span>Observed Latency: <strong className="text-slate-200">{outA?.latencyMs || 0} ms</strong></span>
                <span>Tokens: <strong className="text-slate-200">{outA?.tokensUsed || 0}</strong></span>
                <span>Cost: <strong className="text-slate-200">${(outA?.estimatedCostUsd || 0).toFixed(4)}</strong></span>
              </div>
            </div>

            <div className="space-y-1">
              <span className="text-[10px] font-mono text-slate-400 uppercase font-bold">Raw Output:</span>
              <pre className="p-4 rounded-xl bg-black/80 border border-white/10 text-[11px] font-mono text-cyan-100 whitespace-pre-wrap leading-relaxed max-h-72 overflow-y-auto">
                {outA?.rawOutputText || 'No output generated'}
              </pre>
            </div>
          </div>

          {/* AI Judge Evaluation & Manual Override */}
          <div className="p-3.5 rounded-xl bg-surface/80 border border-white/10 space-y-2.5 font-mono text-xs">
            <div className="flex items-center justify-between">
              <span className="text-[11px] font-bold text-cyan-300 flex items-center gap-1.5">
                <Sparkles className="h-3.5 w-3.5 text-cyan-400" />
                AI Judge Assessment
              </span>
              <span className="text-[10px] text-slate-400">JSON Valid: {outA?.isStructuredJsonValid ? '✓ YES' : '✕ NO'}</span>
            </div>
            <p className="text-[11px] text-slate-300 font-sans leading-relaxed">
              Output conforms strongly to task constraints with high domain relevance and zero hallucinations.
            </p>
            {/* Manual score slider */}
            <div className="flex items-center space-x-3 pt-1 border-t border-white/10">
              <span className="text-[10px] text-slate-400 flex items-center gap-1">
                <Sliders className="h-3 w-3" /> Override:
              </span>
              <input
                type="range"
                min="0"
                max="100"
                value={scoreA}
                onChange={(e) => setManualScoreA(Number(e.target.value))}
                className="flex-1 accent-cyan-400 cursor-pointer"
              />
              <span className="text-xs font-bold text-cyan-300 w-8 text-right">{scoreA}%</span>
            </div>
          </div>
        </div>

        {/* Model B Column */}
        <div className="glass-card p-6 rounded-2xl border border-violet-500/30 shadow-neon-violet space-y-4 flex flex-col justify-between">
          <div className="space-y-3">
            <div className="flex items-center justify-between border-b border-white/10 pb-3">
              <div>
                <span className="text-[10px] font-mono font-bold text-violet-400 uppercase">MODEL B OUTPUT</span>
                <h4 className="text-sm font-bold text-white font-mono">{resB?.modelName}</h4>
              </div>
              <div className="text-right">
                <span className="text-xl font-black font-mono text-violet-300">{scoreB}%</span>
                <span className="text-[10px] text-slate-400 block font-mono">
                  {manualScoreB !== null ? '(Overridden)' : outB?.evaluationMode}
                </span>
              </div>
            </div>

            <div className="space-y-1.5 font-mono text-xs text-slate-400">
              <div className="flex justify-between">
                <span>Observed Latency: <strong className="text-slate-200">{outB?.latencyMs || 0} ms</strong></span>
                <span>Tokens: <strong className="text-slate-200">{outB?.tokensUsed || 0}</strong></span>
                <span>Cost: <strong className="text-slate-200">${(outB?.estimatedCostUsd || 0).toFixed(4)}</strong></span>
              </div>
            </div>

            <div className="space-y-1">
              <span className="text-[10px] font-mono text-slate-400 uppercase font-bold">Raw Output:</span>
              <pre className="p-4 rounded-xl bg-black/80 border border-white/10 text-[11px] font-mono text-violet-100 whitespace-pre-wrap leading-relaxed max-h-72 overflow-y-auto">
                {outB?.rawOutputText || 'No output generated'}
              </pre>
            </div>
          </div>

          {/* AI Judge Evaluation & Manual Override */}
          <div className="p-3.5 rounded-xl bg-surface/80 border border-white/10 space-y-2.5 font-mono text-xs">
            <div className="flex items-center justify-between">
              <span className="text-[11px] font-bold text-violet-300 flex items-center gap-1.5">
                <Sparkles className="h-3.5 w-3.5 text-violet-400" />
                AI Judge Assessment
              </span>
              <span className="text-[10px] text-slate-400">JSON Valid: {outB?.isStructuredJsonValid ? '✓ YES' : '✕ NO'}</span>
            </div>
            <p className="text-[11px] text-slate-300 font-sans leading-relaxed">
              Demonstrates deep requirements reasoning with precise boundary analysis and ISO 29148 compliance.
            </p>
            {/* Manual score slider */}
            <div className="flex items-center space-x-3 pt-1 border-t border-white/10">
              <span className="text-[10px] text-slate-400 flex items-center gap-1">
                <Sliders className="h-3 w-3" /> Override:
              </span>
              <input
                type="range"
                min="0"
                max="100"
                value={scoreB}
                onChange={(e) => setManualScoreB(Number(e.target.value))}
                className="flex-1 accent-violet-400 cursor-pointer"
              />
              <span className="text-xs font-bold text-violet-300 w-8 text-right">{scoreB}%</span>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
